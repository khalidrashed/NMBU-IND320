import streamlit as st
from data_loader import load_data, csv_path

st.set_page_config(
    page_title="Reservoir Data Analysis",
    page_icon="💧",
    layout="wide",
)

st.title("💧 Reservoir Data Analysis")

st.write(
    "This Streamlit application provides an interactive view of the "
    "Norwegian reservoir dataset. Part of the IND320 portfolio."
)

st.header("Welcome")

st.write(
    "Use the pages in the sidebar to explore the application:\n\n"
    "- **Data Table** — view the reservoir dataset in a table, including "
    "an inline sparkline for the first month.\n"
    "- **Plot** — interactively plot columns over a selected month range.\n"
    "- **About** — read the project description, AI usage, and work log.\n"
    "- **ENTSO-E** — explore electricity transfers to and from Norway."
)

st.subheader("Quick dataset summary")

try:
    df = load_data()

    c1, c2, c3 = st.columns(3)

    c1.metric("Rows", f"{len(df):,}")
    c2.metric("Columns", f"{df.shape[1]}")

    if "date" in df.columns and not df.empty:
        c3.metric(
            "Period",
            f"{df['date'].min().date()} → {df['date'].max().date()}",
        )

    with st.expander("Preview first 5 rows"):
        st.dataframe(df.head(), use_container_width=True)

except FileNotFoundError:
    st.error(
        f"Could not find reservoirs.csv. Looked here: `{csv_path()}`"
    )

except Exception as e:
    st.error(f"Could not load reservoir data: {e}")

